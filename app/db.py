"""Storage: leads, suppression list, per-lead event log, query history, HTTP cache, users.

Two backends with the same API:
  * SQLite    (default; a file, for laptops and VMs)
  * Postgres  (when DATABASE_URL is set, e.g. Supabase; for Vercel/serverless)
Rows behave like both dicts and tuples: row["company"], row[0], dict(row).
"""
from __future__ import annotations

import contextlib
import json
import os
import secrets
import sqlite3
import threading
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any, Iterable, Iterator

SCHEMA = """
CREATE TABLE IF NOT EXISTS leads (
    id              {PK},
    company         TEXT NOT NULL,
    website         TEXT,
    domain          TEXT UNIQUE,
    source          TEXT,
    source_url      TEXT,
    query           TEXT,
    snippet         TEXT,
    city_hint       TEXT,
    location        TEXT,
    city            TEXT,
    state           TEXT,
    tier            TEXT,
    email           TEXT,
    all_emails      TEXT,
    phone           TEXT,
    whatsapp        INTEGER DEFAULT 0,
    linkedin        TEXT,
    industry        TEXT,
    signals         TEXT,          -- JSON from Enrichment Agent
    rule_score      REAL,
    llm_score       REAL,
    score           INTEGER,
    needs           TEXT,          -- JSON list
    reasons         TEXT,          -- JSON list
    observed_problem TEXT,
    matched_project TEXT,
    match_reason    TEXT,
    sender_id       TEXT,          -- team.yaml member who signs/sends this email
    sent_from       TEXT,          -- mailbox id used ('shared' or 'member:<id>')
    email_subject   TEXT,
    email_body      TEXT,
    validation      TEXT,          -- JSON list of rule violations (empty = clean)
    status          TEXT NOT NULL DEFAULT 'discovered',
    error           TEXT,
    message_id      TEXT,
    created_at      TEXT NOT NULL,
    updated_at      TEXT NOT NULL,
    approved_at     TEXT,
    sent_at         TEXT
);

CREATE TABLE IF NOT EXISTS suppression (
    value       TEXT PRIMARY KEY,  -- lower-cased email or domain
    kind        TEXT NOT NULL,     -- email | domain
    reason      TEXT NOT NULL,     -- emailed | bounced | replied | unsubscribed | manual
    created_at  TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS events (
    id       {PK},
    lead_id  INTEGER,
    ts       TEXT NOT NULL,
    agent    TEXT NOT NULL,
    event    TEXT NOT NULL,
    detail   TEXT
);
CREATE INDEX IF NOT EXISTS idx_events_lead ON events(lead_id);

CREATE TABLE IF NOT EXISTS queries (
    query    TEXT PRIMARY KEY,
    source   TEXT,
    ran_at   TEXT,
    results  INTEGER
);

CREATE TABLE IF NOT EXISTS users (
    username       TEXT PRIMARY KEY,   -- team.yaml member id
    password_hash  TEXT NOT NULL,
    is_admin       INTEGER NOT NULL DEFAULT 0,
    must_change    INTEGER NOT NULL DEFAULT 0,
    created_at     TEXT NOT NULL,
    last_login_at  TEXT
);

CREATE TABLE IF NOT EXISTS login_failures (
    id        {PK},
    username  TEXT NOT NULL,
    ip        TEXT,
    ts        TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS http_cache (
    url          TEXT PRIMARY KEY,
    fetched_at   TEXT NOT NULL,
    status       INTEGER,
    final_url    TEXT,
    content_type TEXT,
    rendered     INTEGER DEFAULT 0,
    body         TEXT
);

CREATE TABLE IF NOT EXISTS kv (
    key         TEXT PRIMARY KEY,
    value       TEXT,
    updated_at  TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS leases (
    name        TEXT PRIMARY KEY,
    token       TEXT NOT NULL,
    expires_at  TEXT NOT NULL
);
"""

PK = {"sqlite": "INTEGER PRIMARY KEY AUTOINCREMENT", "postgres": "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"}

# Indexes are created after migrations so older databases get the new columns first.
INDEXES = """
CREATE INDEX IF NOT EXISTS idx_leads_status ON leads(status);
CREATE INDEX IF NOT EXISTS idx_leads_sent ON leads(sent_from, sent_at);
"""

# Columns added after the first release: ALTER TABLE on older databases.
MIGRATIONS = {"leads": {"sender_id": "TEXT", "sent_from": "TEXT"},
              "users": {"must_change": "INTEGER NOT NULL DEFAULT 0"}}

# Lead status lifecycle
STATUSES = [
    "discovered",      # Research Agent found it
    "no_website",      # directory listing without a site (kept for manual follow-up)
    "enriched",        # Enrichment Agent extracted details
    "unreachable",     # site down / non-HTML
    "blocked_robots",  # robots.txt disallows us
    "discarded",       # Qualification score below threshold / not ICP
    "qualified",
    "matched",
    "needs_contact",   # qualified + drafted, but no public email address
    "drafted",         # email written, waiting for human review
    "approved",
    "sending",         # claimed by a sender (guards against double sends)
    "rejected",
    "sent",
    "failed",
    "suppressed",
    "bounced",
    "replied",
]


def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


class AlreadyRunning(RuntimeError):
    pass


class Row(dict):
    """dict that also allows positional access, like sqlite3.Row."""

    __slots__ = ()

    def __getitem__(self, key):
        if isinstance(key, int):
            return list(self.values())[key]
        return dict.__getitem__(self, key)


def _clean(v: Any) -> Any:
    # Postgres rejects NUL characters in text; scraped HTML sometimes has them.
    return v.replace("\x00", "") if isinstance(v, str) else v


class DB:
    def __init__(self, target: str | Path):
        """target: a SQLite file path, or a postgres:// URL."""
        self._lock = threading.RLock()
        self.url = str(target)
        self.pg = self.url.startswith(("postgres://", "postgresql://"))
        self.backend = "postgres" if self.pg else "sqlite"
        self.path = None if self.pg else Path(target)
        self._connect()
        self._init_schema()

    # ------------------------------------------------------------ plumbing
    def _connect(self) -> None:
        if self.pg:
            import psycopg

            def row_factory(cursor):
                names = [c.name for c in cursor.description] if cursor.description else []
                return lambda values: Row(zip(names, values))

            # prepare_threshold=None: works through PgBouncer/Supavisor transaction pooling.
            self.conn = psycopg.connect(self.url, autocommit=True, prepare_threshold=None,
                                        connect_timeout=15, row_factory=row_factory)
        else:
            self.path.parent.mkdir(parents=True, exist_ok=True)
            self.conn = sqlite3.connect(str(self.path), check_same_thread=False, isolation_level=None, timeout=30)
            self.conn.row_factory = lambda cur, row: Row(zip([d[0] for d in cur.description], row))
            self.conn.execute("PRAGMA journal_mode=WAL")

    def _init_schema(self) -> None:
        ddl = SCHEMA.replace("{PK}", PK[self.backend])
        if self.pg:
            for stmt in (s.strip() for s in ddl.split(";")):
                if stmt and not stmt.startswith("--"):
                    self.execute(stmt)
        else:
            self.conn.executescript(ddl)
        self._migrate()
        for stmt in (s.strip() for s in INDEXES.split(";")):
            if stmt:
                self.execute(stmt)
        if self.pg:
            self._lock_down_api_access()

    TABLES = ("leads", "suppression", "events", "queries", "users", "login_failures", "http_cache", "kv", "leases")

    def _lock_down_api_access(self) -> None:
        """Supabase exposes the public schema over its REST API. Row-level security with no
        policies blocks that API (the table owner, i.e. this app, is unaffected), and API roles
        lose their grants. Safe to run on every start."""
        for t in self.TABLES:
            self.execute(f"ALTER TABLE {t} ENABLE ROW LEVEL SECURITY")
        self.execute("""
            DO $$ DECLARE r text; BEGIN
              FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
                IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
                  EXECUTE format('REVOKE ALL ON leads, suppression, events, queries, users, login_failures, '
                                 'http_cache, kv, leases FROM %I', r);
                END IF;
              END LOOP;
            END $$""")

    def _columns(self, table: str) -> set[str]:
        if self.pg:
            return {r[0] for r in self.query(
                "SELECT column_name FROM information_schema.columns WHERE table_schema = current_schema() "
                "AND table_name = ?", (table,))}
        return {r[1] for r in self.query(f"PRAGMA table_info({table})")}

    def _migrate(self) -> None:
        for table, cols in MIGRATIONS.items():
            have = self._columns(table)
            for col, typ in cols.items():
                if col not in have:
                    self.execute(f"ALTER TABLE {table} ADD COLUMN {col} {typ}")

    def _sql(self, q: str) -> str:
        return q.replace("?", "%s") if self.pg else q

    def execute(self, q: str, args: Iterable = ()):
        """Run a statement; returns the cursor (use .rowcount / .fetchall())."""
        args = tuple(_clean(a) for a in args)
        # psycopg parses %-placeholders only when parameters are passed; pass None when there are none.
        params = args if (args or not self.pg) else None
        with self._lock:
            try:
                return self.conn.execute(self._sql(q), params)
            except Exception as e:
                if not self.pg or not _is_disconnect(e):
                    raise
                # Serverless instances can be frozen long enough for the pooler to drop us.
                self._connect()
                return self.conn.execute(self._sql(q), params)

    def query(self, q: str, args: Iterable = ()) -> list[Row]:
        return self.execute(q, args).fetchall()

    def one(self, q: str, args: Iterable = ()) -> Row | None:
        return self.execute(q, args).fetchone()

    def scalar(self, q: str, args: Iterable = ()) -> Any:
        row = self.one(q, args)
        return row[0] if row else None

    # ----------------------------------------------------------- locking
    @contextlib.contextmanager
    def lock(self, name: str, ttl_seconds: int) -> Iterator[None]:
        """Exclusive across processes and servers. Raises AlreadyRunning if held.

        SQLite: an OS file lock next to the database (released if the process dies).
        Postgres: a lease row that expires after ttl_seconds (works across serverless instances).
        """
        if not self.pg:
            from app.tools.locks import AlreadyRunning as FileLocked, exclusive

            try:
                with exclusive(self.path.with_suffix(f".{name}.lock")):
                    yield
            except FileLocked as e:
                raise AlreadyRunning(str(e)) from e
            return
        token = secrets.token_hex(8)
        expires = (datetime.now(timezone.utc) + timedelta(seconds=ttl_seconds)).isoformat(timespec="seconds")
        got = self.one(
            "INSERT INTO leases(name, token, expires_at) VALUES (?,?,?) "
            "ON CONFLICT(name) DO UPDATE SET token=excluded.token, expires_at=excluded.expires_at "
            "WHERE leases.expires_at < ? RETURNING token", (name, token, expires, now()))
        if not got or got[0] != token:
            raise AlreadyRunning(f"lease '{name}' is held")
        try:
            yield
        finally:
            self.execute("DELETE FROM leases WHERE name=? AND token=?", (name, token))

    # --------------------------------------------------------------- kv
    def kv_get(self, key: str, default: str | None = None) -> str | None:
        v = self.scalar("SELECT value FROM kv WHERE key=?", (key,))
        return default if v is None else v

    def kv_set(self, key: str, value: str) -> None:
        self.execute("INSERT INTO kv(key, value, updated_at) VALUES (?,?,?) "
                     "ON CONFLICT(key) DO UPDATE SET value=excluded.value, updated_at=excluded.updated_at",
                     (key, value, now()))

    # ---------------------------------------------------------------- leads
    def find_lead(self, domain: str | None = None, company: str | None = None, city: str | None = None):
        if domain:
            return self.one("SELECT * FROM leads WHERE domain=?", (domain,))
        if company:
            return self.one(
                "SELECT * FROM leads WHERE lower(company)=lower(?) AND coalesce(lower(city_hint),'')=coalesce(lower(?),'')",
                (company, city))
        return None

    def add_lead(self, **fields: Any) -> int | None:
        """Insert unless the domain (or company+city when no domain) already exists."""
        if self.find_lead(domain=fields.get("domain")) if fields.get("domain") else self.find_lead(
                company=fields.get("company"), city=fields.get("city_hint")):
            return None
        fields.setdefault("status", "discovered")
        fields["created_at"] = fields["updated_at"] = now()
        cols = ", ".join(fields)
        qs = ", ".join("?" for _ in fields)
        row = self.one(f"INSERT INTO leads ({cols}) VALUES ({qs}) ON CONFLICT DO NOTHING RETURNING id",
                       list(fields.values()))
        return row[0] if row else None

    def update_lead(self, lead_id: int, **fields: Any) -> None:
        for k, v in list(fields.items()):
            if isinstance(v, (list, dict)):
                fields[k] = json.dumps(v, ensure_ascii=False)
        fields["updated_at"] = now()
        sets = ", ".join(f"{k}=?" for k in fields)
        self.execute(f"UPDATE leads SET {sets} WHERE id=?", [*fields.values(), lead_id])

    def claim_lead(self, lead_id: int, from_status: str, to_status: str) -> bool:
        """Atomically move a lead between statuses; False if someone else got there first."""
        return self.execute("UPDATE leads SET status=?, updated_at=? WHERE id=? AND status=?",
                            (to_status, now(), lead_id, from_status)).rowcount == 1

    def get_lead(self, lead_id: int):
        return self.one("SELECT * FROM leads WHERE id=?", (lead_id,))

    def leads_by_status(self, *statuses: str, limit: int | None = None) -> list[Row]:
        q = (f"SELECT * FROM leads WHERE status IN ({','.join('?' * len(statuses))}) "
             "ORDER BY score DESC NULLS LAST, id")
        if limit:
            q += f" LIMIT {int(limit)}"
        return self.query(q, statuses)

    def all_leads(self, status: str | None = None) -> list[Row]:
        if status:
            return self.query("SELECT * FROM leads WHERE status=? ORDER BY id", (status,))
        return self.query("SELECT * FROM leads ORDER BY id")

    def status_counts(self) -> dict[str, int]:
        return {r[0]: r[1] for r in self.query("SELECT status, count(*) FROM leads GROUP BY status")}

    def sent_since(self, since_iso: str, mailbox: str | None = None) -> int:
        """Emails actually sent since a time, optionally from one mailbox (daily limits are per mailbox)."""
        if mailbox:
            return self.scalar("SELECT count(*) FROM leads WHERE sent_from=? AND sent_at>=?", (mailbox, since_iso))
        return self.scalar("SELECT count(*) FROM leads WHERE sent_at>=?", (since_iso,))

    def assigned_counts(self) -> dict[str, int]:
        """Open leads per team member (used for round-robin assignment)."""
        return {r[0]: r[1] for r in self.query(
            "SELECT sender_id, count(*) FROM leads WHERE sender_id IS NOT NULL "
            "AND status IN ('matched','drafted','needs_contact','approved') GROUP BY sender_id")}

    # ----------------------------------------------------------- suppression
    def suppress(self, value: str, kind: str, reason: str) -> None:
        self.execute(
            "INSERT INTO suppression(value, kind, reason, created_at) VALUES (?,?,?,?) "
            "ON CONFLICT(value) DO UPDATE SET reason=excluded.reason",
            (value.lower().strip(), kind, reason, now()))

    def is_suppressed(self, email: str | None, domain: str | None) -> str | None:
        """Returns the suppression reason, or None if OK to contact."""
        keys = [k.lower() for k in (email, domain) if k]
        if email and "@" in email:
            keys.append(email.split("@", 1)[1].lower())
        for k in keys:
            reason = self.scalar("SELECT reason FROM suppression WHERE value=?", (k,))
            if reason:
                return reason
        return None

    def suppression_list(self) -> list[Row]:
        return self.query("SELECT * FROM suppression ORDER BY created_at DESC")

    # ----------------------------------------------------------------- users
    def get_user(self, username: str):
        return self.one("SELECT * FROM users WHERE username=?", (username,))

    def list_users(self) -> list[Row]:
        return self.query("SELECT * FROM users ORDER BY username")

    def upsert_user(self, username: str, password_hash: str, is_admin: bool, must_change: bool = False) -> None:
        self.execute(
            "INSERT INTO users(username, password_hash, is_admin, must_change, created_at) VALUES (?,?,?,?,?) "
            "ON CONFLICT(username) DO UPDATE SET password_hash=excluded.password_hash, is_admin=excluded.is_admin, "
            "must_change=excluded.must_change",
            (username, password_hash, int(is_admin), int(must_change), now()))

    def set_password(self, username: str, password_hash: str, must_change: bool = False) -> None:
        self.execute("UPDATE users SET password_hash=?, must_change=? WHERE username=?",
                     (password_hash, int(must_change), username))

    def delete_user(self, username: str) -> bool:
        return self.execute("DELETE FROM users WHERE username=?", (username,)).rowcount > 0

    def record_login(self, username: str, ok: bool, ip: str | None) -> None:
        if ok:
            self.execute("UPDATE users SET last_login_at=? WHERE username=?", (now(), username))
            self.execute("DELETE FROM login_failures WHERE username=?", (username,))
        else:
            self.execute("INSERT INTO login_failures(username, ip, ts) VALUES (?,?,?)", (username, ip, now()))

    def recent_login_failures(self, username: str, minutes: int) -> int:
        since = (datetime.now(timezone.utc) - timedelta(minutes=minutes)).isoformat(timespec="seconds")
        return self.scalar("SELECT count(*) FROM login_failures WHERE username=? AND ts>=?", (username, since))

    # ---------------------------------------------------------------- backup
    def backup(self, target_dir: str | Path, keep_days: int = 14) -> Path:
        """Consistent online copy of a SQLite database (safe while the web app and timers run)."""
        if self.pg:
            raise RuntimeError("Postgres backups are handled by the database host (e.g. Supabase dashboard).")
        target_dir = Path(target_dir)
        target_dir.mkdir(parents=True, exist_ok=True)
        dest = target_dir / f"leads-{datetime.now().strftime('%Y%m%d-%H%M%S')}.db"
        out = sqlite3.connect(str(dest))
        with out:
            self.conn.backup(out)
        out.close()
        cutoff = datetime.now().timestamp() - keep_days * 86400
        for old in target_dir.glob("leads-*.db"):
            if old.stat().st_mtime < cutoff:
                old.unlink()
        return dest

    def last_event(self, agent: str, event: str | None = None):
        q = "SELECT * FROM events WHERE agent=?" + (" AND event=?" if event else "") + " ORDER BY id DESC LIMIT 1"
        return self.one(q, (agent, event) if event else (agent,))

    # ---------------------------------------------------------------- events
    def log(self, agent: str, event: str, lead_id: int | None = None, detail: Any = None) -> None:
        if detail is not None and not isinstance(detail, str):
            detail = json.dumps(detail, ensure_ascii=False, default=str)
        self.execute("INSERT INTO events(lead_id, ts, agent, event, detail) VALUES (?,?,?,?,?)",
                     (lead_id, now(), agent, event, detail))

    def events_for(self, lead_id: int) -> list[Row]:
        return self.query("SELECT * FROM events WHERE lead_id=? ORDER BY id", (lead_id,))

    # --------------------------------------------------------------- queries
    def query_ran(self, query: str) -> bool:
        return self.one("SELECT 1 FROM queries WHERE query=?", (query,)) is not None

    def record_query(self, query: str, source: str, results: int) -> None:
        self.execute(
            "INSERT INTO queries(query, source, ran_at, results) VALUES (?,?,?,?) "
            "ON CONFLICT(query) DO UPDATE SET source=excluded.source, ran_at=excluded.ran_at, results=excluded.results",
            (query, source, now(), results))

    def queries_since(self, since_iso: str) -> int:
        return self.scalar("SELECT count(*) FROM queries WHERE ran_at>=?", (since_iso,))

    # ------------------------------------------------------------ http cache
    def cache_get(self, url: str, max_age_hours: float):
        row = self.one("SELECT * FROM http_cache WHERE url=?", (url,))
        if not row:
            return None
        age = datetime.now(timezone.utc) - datetime.fromisoformat(row["fetched_at"])
        return row if age < timedelta(hours=max_age_hours) else None

    def cache_put(self, url: str, status: int, final_url: str, content_type: str, body: str, rendered: bool) -> None:
        if self.pg:
            body = body[:200_000]  # keep the hosted database small
        self.execute(
            "INSERT INTO http_cache(url, fetched_at, status, final_url, content_type, rendered, body) "
            "VALUES (?,?,?,?,?,?,?) ON CONFLICT(url) DO UPDATE SET fetched_at=excluded.fetched_at, "
            "status=excluded.status, final_url=excluded.final_url, content_type=excluded.content_type, "
            "rendered=excluded.rendered, body=excluded.body",
            (url, now(), status, final_url, content_type, int(rendered), body))

    def prune_cache(self, older_than_hours: float) -> int:
        cutoff = (datetime.now(timezone.utc) - timedelta(hours=older_than_hours)).isoformat(timespec="seconds")
        return self.execute("DELETE FROM http_cache WHERE fetched_at<?", (cutoff,)).rowcount


def _is_disconnect(e: Exception) -> bool:
    try:
        import psycopg
    except ImportError:  # pragma: no cover
        return False
    return isinstance(e, (psycopg.OperationalError, psycopg.InterfaceError))


def open_db(cfg) -> DB:
    """DATABASE_URL (Postgres) if set, otherwise the SQLite file from settings."""
    url = os.getenv("DATABASE_URL", "").strip()
    if not url and os.getenv("VERCEL"):
        raise RuntimeError("DATABASE_URL is not set: Vercel has no persistent disk, a Postgres database is required")
    return DB(url) if url else DB(cfg.path(cfg.settings["storage"]["db_path"]))


def loads(value: str | None, default: Any = None) -> Any:
    if not value:
        return default
    try:
        return json.loads(value)
    except (TypeError, ValueError):
        return default


def rows_to_dicts(rows: Iterable[Row]) -> list[dict]:
    return [dict(r) for r in rows]
